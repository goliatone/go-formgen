// Generates src/theme/grid-layout.css: the stylesheet half of the vanilla
// renderer's grid layout contract. The renderer emits layout intent as data
// attributes instead of inline `style` attributes so forms render under a
// `style-src 'self'` Content-Security-Policy:
//
//   grid container  data-formgen-columns="<n>"  data-formgen-gutter="sm|md|lg"
//   field wrapper   data-formgen-span="<n>" [data-formgen-start="<n>"] [data-formgen-row="<n>"]
//                   plus -sm/-md/-lg/-xl/-2xl variants applied inside min-width media queries
//
// Run `npm run build:grid` after changing the bounds below; build-theme.mjs
// refuses to build when the committed file is stale.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** Highest column count, span, start, and row the bundled stylesheet covers. */
export const GRID_MAX_TRACKS = 24;

/** layout.gutter values and the --formgen-grid-gap they select. */
export const GRID_GUTTERS = Object.freeze({ sm: "1rem", md: "1.5rem", lg: "2rem" });

/** Breakpoint suffixes and their min-width thresholds (Tailwind defaults). */
export const GRID_BREAKPOINTS = Object.freeze([
  ["sm", 640],
  ["md", 768],
  ["lg", 1024],
  ["xl", 1280],
  ["2xl", 1536],
]);

const __dirname = dirname(fileURLToPath(import.meta.url));
export const GRID_LAYOUT_FILE = resolve(__dirname, "..", "src", "theme", "grid-layout.css");

function placementRules(suffix, indent = "") {
  const lines = [];
  for (let n = 1; n <= GRID_MAX_TRACKS; n += 1) {
    lines.push(`${indent}[data-formgen-span${suffix}="${n}"] { grid-column-end: span ${n}; }`);
  }
  for (let n = 1; n <= GRID_MAX_TRACKS; n += 1) {
    lines.push(`${indent}[data-formgen-start${suffix}="${n}"] { grid-column-start: ${n}; }`);
  }
  for (let n = 1; n <= GRID_MAX_TRACKS; n += 1) {
    lines.push(`${indent}[data-formgen-row${suffix}="${n}"] { grid-row-start: ${n}; }`);
  }
  return lines;
}

export function renderGridLayoutCSS() {
  const out = [
    "/* Generated by client/scripts/grid-layout.mjs; run `npm run build:grid` instead of editing. */",
    "/* Grid layout contract: the vanilla renderer emits data-formgen-columns and",
    "   data-formgen-gutter on the grid container and data-formgen-span, -start, -row",
    "   (plus -sm/-md/-lg/-xl/-2xl variants) on field wrappers; these rules place them.",
    "   Single attribute selectors keep specificity at 0,1,0 so host CSS can override. */",
    "",
    "/* layout.gutter -> gap variable consumed by .formgen-grid */",
  ];
  for (const [name, gap] of Object.entries(GRID_GUTTERS)) {
    out.push(`[data-formgen-gutter="${name}"] { --formgen-grid-gap: ${gap}; }`);
  }
  out.push("", "/* layout.gridColumns */");
  for (let n = 1; n <= GRID_MAX_TRACKS; n += 1) {
    out.push(`[data-formgen-columns="${n}"] { grid-template-columns: repeat(${n}, minmax(0, 1fr)); }`);
  }
  out.push("", "/* layout.span / layout.start / layout.row */");
  out.push(...placementRules(""));
  for (const [breakpoint, minWidth] of GRID_BREAKPOINTS) {
    out.push("", `/* layout.*.${breakpoint} */`, `@media (min-width: ${minWidth}px) {`);
    out.push(...placementRules(`-${breakpoint}`, "  "));
    out.push("}");
  }
  return `${out.join("\n")}\n`;
}

export async function readCommittedGridLayoutCSS(file = GRID_LAYOUT_FILE) {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return null;
    }
    throw error;
  }
}

export async function writeGridLayoutCSS(file = GRID_LAYOUT_FILE) {
  const next = renderGridLayoutCSS();
  if ((await readCommittedGridLayoutCSS(file)) === next) {
    return false;
  }
  await writeFile(file, next, "utf8");
  return true;
}

const invokedDirectly =
  typeof process.argv[1] === "string" &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url;

if (invokedDirectly) {
  writeGridLayoutCSS()
    .then((changed) => {
      console.log(`[formgen:grid] ${changed ? "wrote" : "up to date:"} src/theme/grid-layout.css`);
    })
    .catch((error) => {
      console.error("[formgen:grid] generation failed:", error);
      process.exit(1);
    });
}
